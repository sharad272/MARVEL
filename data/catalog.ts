/**
 * The curated Marvel catalog.
 *
 * This is hand-maintained rather than derived from a TMDB query, because
 * no TMDB list cleanly expresses "every Marvel screen production, grouped
 * by continuity, ordered by in-universe chronology". TMDB then enriches
 * each row with artwork, runtimes, trailers and streaming availability.
 * `lib/catalog/refresh.ts` also discovers newly listed MCU titles so the
 * app does not wait on a hand edit for every new release.
 *
 * `tmdbId` is a *hint*. The sync job verifies the fetched title matches
 * and falls back to a search-by-name-and-year when it doesn't, so a stale
 * or wrong id self-heals instead of poisoning the catalog.
 *
 * `chrono` is spaced by 10 so titles can be slotted between existing
 * entries without renumbering the world.
 */

